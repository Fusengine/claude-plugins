/**
 * Regenerates docs/img/statusline-mod.mp4 and docs/img/statusline-mod.gif.
 *
 *   bun docs/demo/statusline-mod/motion-render.js [workDir]     (run from anywhere)
 *
 * 1. bundles the mod's real drawing functions (motion-entry.js -> motion-bundle.js);
 * 2. captures index.html frame by frame in headless Chrome (motion-capture.js);
 * 3. encodes with ffmpeg: H.264 1600 px, then a palettegen/paletteuse GIF at 960 px.
 * Needs: bun, ffmpeg, Chrome or Chromium (CHROME_BIN to override).
 */
import { mkdtempSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { capture } from "./motion-capture.js";

const HERE = import.meta.dir;
const ROOT = resolve(HERE, "../../..");
const IMG = join(ROOT, "docs/img");
const FPS = 30;
/** Stage: 1280x720 CSS px at 1.25 = 1600x900 device px. */
const STAGE = { width: 1280, height: 720, scale: 1.25 };

/** Runs a command, failing loudly. */
function run(cmd) {
	const p = Bun.spawnSync(cmd, { stdout: "inherit", stderr: "inherit" });
	if (p.exitCode !== 0) throw new Error(`failed: ${cmd.join(" ")}`);
}

/** Bundles the mod's functions for the browser (IIFE, `globalThis.SL`). */
async function bundle() {
	const out = await Bun.build({ entrypoints: [join(HERE, "motion-entry.js")], format: "iife", target: "browser" });
	if (!out.success) throw new Error(out.logs.join("\n"));
	await Bun.write(join(HERE, "motion-bundle.js"), `/* generated by motion-render.js from motion-entry.js — do not edit */\n${await out.outputs[0].text()}`);
}

/** Human size of a file. */
const size = (p) => `${(statSync(p).size / 1024 / 1024).toFixed(2)} MB`;

async function main() {
	const work = process.argv[2] ? resolve(process.argv[2]) : mkdtempSync(join(tmpdir(), "statusline-mod-"));
	const frames = join(work, "frames");
	rmSync(frames, { recursive: true, force: true });
	console.log("› bundling the mod's drawing functions");
	await bundle();
	console.log(`› capturing frames into ${frames}`);
	const n = await capture({
		url: `file://${join(HERE, "index.html")}?capture`,
		outDir: frames,
		profile: join(work, "chrome-profile"),
		fps: FPS,
		...STAGE,
	});
	const input = ["-framerate", String(FPS), "-i", join(frames, "frame_%04d.png")];
	const mp4 = join(IMG, "statusline-mod.mp4");
	const gif = join(IMG, "statusline-mod.gif");
	console.log("› encoding mp4");
	run(["ffmpeg", "-y", "-loglevel", "error", ...input, "-vf", "scale=1600:-2:flags=lanczos",
		"-c:v", "libx264", "-preset", "slow", "-crf", "22", "-tune", "animation",
		"-threads", "1", "-x264-params", "threads=1:sliced-threads=0:sync-lookahead=0",
		"-pix_fmt", "yuv420p", "-movflags", "+faststart", mp4]);
	console.log("› encoding gif");
	const graph = "fps=15,scale=960:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=96:stats_mode=diff[p];" +
		"[b][p]paletteuse=dither=bayer:bayer_scale=5:diff_mode=rectangle";
	run(["ffmpeg", "-y", "-loglevel", "error", ...input, "-vf", graph, "-loop", "0", gif]);
	console.log(`✓ ${n} frames, ${(n / FPS).toFixed(1)} s · mp4 ${size(mp4)} · gif ${size(gif)}`);
}

await main();
